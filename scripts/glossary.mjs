/** Виправлення типових помилок машинного перекладу. */
const FIXES = [
  [/\bмука\b/gi, 'борошно'],
  [/\bмуки\b/gi, 'борошна'],
  [/\bмуку\b/gi, 'борошно'],
  [/\bмукою\b/gi, 'борошном'],
  [/\bсливочн(ого|е|им|ому) масл/gi, 'вершков$1 масл'],
  [/\bсливки\b/gi, 'вершки'],
  [/\bсливок\b/gi, 'вершків'],
  [/\bкольорова капуста/gi, 'цвітна капуста'],
  [/\bкабачок цукіні/gi, 'цукіні'],
  [/\bнагрійте духовку/gi, 'розігрійте духовку'],
  [/\bпластівців чилі\b/gi, 'пластівців чилі'],
  [/\bтбсп\b/gi, 'ст. л.'],
  [/\bст\.\s?л\b\.?/g, 'ст. л.'],
  [/\bч\.\s?л\b\.?/g, 'ч. л.'],
  [/\bтсп\b/gi, 'ч. л.'],
  [/(\d)\s?С\b/g, '$1 °C'],
  [/(\d)\s?°\s?С\b/g, '$1 °C'],
];

// \b у JS не працює з кирилицею — замінюємо на перевірку «не літера»
const COMPILED = FIXES.map(([re, to]) => [
  new RegExp(re.source.replace(/^\\b/, '(?<![\\p{L}])').replace(/\\b$/, '(?![\\p{L}])').replace(/\\b/g, '(?![\\p{L}])'), re.flags.includes('u') ? re.flags : re.flags + 'u'),
  to,
]);

export function fixText(s) {
  let out = s;
  for (const [re, to] of COMPILED) out = out.replace(re, to);
  return out.replace(/\s+([,.;:!?])/g, '$1').replace(/\s{2,}/g, ' ').trim();
}

