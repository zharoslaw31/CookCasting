/** Загальні виправлення перекладених назв. */
export function fixName(s) {
  return s
    .replace(/^Рецепт\s+/i, '')
    .replace(/подорожник/gi, (m) => (m[0] === 'П' ? 'Плантан' : 'плантан'))
    .replace(/^Фрай з /, 'Стір-фрай з ')
    .replace(/Шакшовка/gi, 'Шакшука')
    .replace(/[.]$/, '')
    .trim();
}
